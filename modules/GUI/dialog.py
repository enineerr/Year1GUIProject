# import tkinter as tk
from tkinter import ttk
from tkinter import StringVar, Toplevel, messagebox


class dialog:
    def __init__(self, students, root) -> None:
        self.students = students
        self.root = root

        # This var is only init here in case the user decides to exit the dialog instantly
        self.__out = None

    def initDialog(self) -> int:
        # 0 -> exit
        # 1 -> open
        # 2 -> new
        self.dialog = Toplevel(self.root)
        new = ttk.Button(self.dialog, text="New File", command=lambda: self.initOut(2))
        new.grid(row=10, column=3, padx=5, pady=5, sticky="SE")
        self.dialog.bind("<Return>", lambda _: new.invoke())
        open = ttk.Button(self.dialog, text="Open", command=lambda: self.initOut(1))
        open.grid(row=10, column=2, padx=5, pady=5, sticky="SE")
        cancel = ttk.Button(self.dialog, text="Cancel", command=lambda: self.initOut(0))
        cancel.grid(row=10, column=1, padx=5, pady=5, sticky="SE")

        new.focus()

        self.dialog.protocol("WM_DELETE_WINDOW", self.dialog.destroy)  # take over exit
        self.dialog.transient(self.root)  # set to be dialong rather than main window
        self.dialog.grab_set()  # prevent input to main window

        # Wait for user to do something
        self.dialog.wait_window()

        return self.__out

    def initOut(self, code: int):
        self.__out = code
        self.dialog.destroy()

    def addGradeDialog(self, inName: str = "", inGrade: str = "") -> dict[str, float] | None:
        self.dialog = Toplevel(self.root)  # init dialog

        ## Define widgets
        # Buttons
        done = ttk.Button(self.dialog, text="Done", command=lambda: self.doneGCB(inGrade))
        done.grid(row=10, column=2, padx=5, pady=5, sticky="SE")
        self.dialog.bind("<Return>", lambda _: done.invoke())
        cancel = ttk.Button(self.dialog, text="Cancel", command=self.dialog.destroy)
        cancel.grid(row=10, column=1, padx=5, pady=5, sticky="SE")
        self.dialog.bind("<Escape>", lambda _: cancel.invoke())
        ## Labels
        # Course Name
        nLabel = ttk.Label(self.dialog, text="Course Name:")
        nLabel.grid(row=0, column=0, padx=5, pady=5, sticky="E")
        # Grade
        idLabel = ttk.Label(self.dialog, text="Grade:")
        idLabel.grid(row=1, column=0, padx=5, pady=5, sticky="E")

        self.__name = StringVar(value=inName)
        self.__grade = StringVar(value=inGrade)

        ## Entries
        # Name
        nEntry = ttk.Entry(self.dialog, textvariable=self.__name)
        nEntry.grid(row=0, column=1, sticky="NWE", padx=5, pady=5, columnspan=2)
        # SID
        checker = (self.dialog.register(self.checkGrade), "%P")
        idEntry = ttk.Entry(self.dialog, validate="key", textvariable=self.__grade, validatecommand=checker)
        idEntry.grid(row=1, column=1, sticky="NWE", padx=5, pady=5, columnspan=2)

        # Focus on name entry for ux
        nEntry.focus()

        self.dialog.protocol("WM_DELETE_WINDOW", self.dialog.destroy)  # take over exit
        self.dialog.transient(self.root)  # set to be dialong rather than main window
        self.dialog.grab_set()  # prevent input to main window

        # Wait for user to do something
        self.dialog.wait_window()

        return self.__out

    def doneGCB(self, inId) -> None:
        # If name is empty, don't try to process anything
        if (self.__name.get() == ""):
            self.cleanup(None)
            return

        # Allow ID to be generated by caller if not selected
        # return 0
        if (self.__grade.get() == ""):
            self.cleanup([str(self.__name.get()).title(), 0])
            return

        # Check if ID is alreay in use, but only if not editting
        if (inId == ""):
            if (float(str(self.__grade.get())) in [s.ID for s in self.students]):
                # If so let the user know and let them restart
                messagebox.showerror("Student ID in use", "The entered student ID is already in use, please try again.")
                self.cleanup(self.addStudentDialog(inName=self.__name.get()))
                return

        self.cleanup([str(self.__name.get()).title(), float(str(self.__grade.get()))])

    def addStudentDialog(self, inName: str = "", inId: str = "") -> list[str | int] | None:
        self.dialog = Toplevel(self.root)  # init dialog

        ## Define widgets
        # Buttons
        done = ttk.Button(self.dialog, text="Done", command=lambda: self.doneSCB(inId))
        done.grid(row=10, column=2, padx=5, pady=5, sticky="SE")
        self.dialog.bind("<Return>", lambda _: done.invoke())
        cancel = ttk.Button(self.dialog, text="Cancel", command=self.dialog.destroy)
        cancel.grid(row=10, column=1, padx=5, pady=5, sticky="SE")
        self.dialog.bind("<Escape>", lambda _: cancel.invoke())
        ## Labels
        # Name
        nLabel = ttk.Label(self.dialog, text="Full Name:")
        nLabel.grid(row=0, column=0, padx=5, pady=5, sticky="E")
        # ID
        idLabel = ttk.Label(self.dialog, text="Student ID:")
        idLabel.grid(row=1, column=0, padx=5, pady=5, sticky="E")
        # ID subtext
        idSubLabel = ttk.Label(self.dialog, text="Leave blank to generate new ID")
        idSubLabel["font"] = "TkTooltipFont"
        idSubLabel.grid(row=3, column=1, sticky="NW", columnspan=2, padx=5)

        self.__name = StringVar(value=inName)
        self.__id = StringVar(value=inId)

        ## Entries
        # Name
        nEntry = ttk.Entry(self.dialog, textvariable=self.__name)
        nEntry.grid(row=0, column=1, sticky="NWE", padx=5, pady=5, columnspan=2)
        # SID
        checker = (self.dialog.register(self.checkID), "%P")
        idEntry = ttk.Entry(self.dialog, validate="key", textvariable=self.__id, validatecommand=checker)
        idEntry.grid(row=1, column=1, sticky="NWE", padx=5, pady=5, columnspan=2)

        # Force ID if passed
        if (inId != ""):
            idEntry.config(state="disabled")
            # Hide ID hint as its not needed
            idSubLabel.destroy()

        # Focus on name entry for ux
        nEntry.focus()

        self.dialog.protocol("WM_DELETE_WINDOW", self.dialog.destroy)  # take over exit
        self.dialog.transient(self.root)  # set to be dialong rather than main window
        self.dialog.grab_set()  # prevent input to main window

        # Wait for user to do something
        self.dialog.wait_window()

        return self.__out

    def doneSCB(self, inId) -> None:
        # If name is empty, don't try to process anything
        if (self.__name.get() == ""):
            self.cleanup(None)
            return

        # Allow ID to be generated by caller if not selected
        # return 0
        if (self.__id.get() == ""):
            self.cleanup([str(self.__name.get()).title(), 0])
            return

        # Check if ID is alreay in use, but only if not editting
        if (inId == ""):
            if (int(str(self.__id.get())) in [s.ID for s in self.students]):
                # If so let the user know and let them restart
                messagebox.showerror("Student ID in use", "The entered student ID is already in use, please try again.")
                self.cleanup(self.addStudentDialog(inName=self.__name.get()))
                return

        self.cleanup([str(self.__name.get()).title(), int(str(self.__id.get()))])

    def cleanup(self, out) -> None:
        self.__out = out
        self.dialog.destroy()

    @staticmethod
    def checkID(val: str) -> bool:
        # If ID is empty allow
        if (len(val) == 0):
            return True
        # In anything else make sure is a number
        return val.isnumeric()

    @staticmethod
    def checkGrade(val: str) -> bool:
        # Allowed numbers (0-9 inc)
        nums = [str(i) for i in range(10)]

        # If ID is empty allow
        if (len(val) == 0):
            return True
        # check flag for dec check
        decCheck = False
        # In anything else make sure is a number with at most 1 "."
        for i in val:
            if (i == "."):
                if (not decCheck):
                    decCheck = True
                else:
                    return False

            elif (i not in nums):
                return False
        # Make sure it isnt larger than 100%
        if (float(val) > 100):
            return False

        # If all other conditions are fine then return True
        return True


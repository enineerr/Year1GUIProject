# import tkinter as tk
from tkinter import ttk
from tkinter import StringVar, Toplevel, messagebox


class dialog:
    def __init__(self, students) -> None:
        self.students = students

    def addStudentDialog(self, root, inName: str = "", inId: str = "") -> list[str | int] | None:
        # Prep this now, so callback function can comunicate.
        self.__out = None

        dialog = Toplevel(root)  # init dialog

        ## Define widgets
        # Buttons
        done = ttk.Button(dialog, text="Done", command=lambda: self.doneCB(inId))
        done.grid(row=10, column=2, padx=5, pady=5, sticky="SE")
        cancel = ttk.Button(dialog, text="Cancel", command=dialog.destroy)
        cancel.grid(row=10, column=1, padx=5, pady=5, sticky="SE")
        ## Labels
        # Name
        nLabel = ttk.Label(dialog, text="Full Name:")
        nLabel.grid(row=0, column=0, padx=5, pady=5, sticky="E")
        # ID
        idLabel = ttk.Label(dialog, text="Student ID:")
        idLabel.grid(row=1, column=0, padx=5, pady=5, sticky="E")
        # ID subtext
        idSubLabel = ttk.Label(dialog, text="Leave blank to generate new ID")
        idSubLabel["font"] = "TkTooltipFont"
        idSubLabel.grid(row=3, column=1, sticky="NW", columnspan=2, padx=5)

        self.__name = StringVar(value=inName)
        self.__id = StringVar(value=inId)

        ## Entries
        # Name
        nEntry = ttk.Entry(dialog, textvariable=self.__name)
        nEntry.grid(row=0, column=1, sticky="NWE", padx=5, pady=5, columnspan=2)
        # SID
        checker = (dialog.register(self.checkID), "%P")
        idEntry = ttk.Entry(dialog, validate="key", textvariable=self.__id, validatecommand=checker)
        idEntry.grid(row=1, column=1, sticky="NWE", padx=5, pady=5, columnspan=2)

        # Force ID if passed
        if (inId != ""):
            idEntry.config(state="disabled")
            # Hide ID hint as its not needed
            idSubLabel.destroy()

        # Focus on name entry for ux
        nEntry.focus()

        dialog.protocol("WM_DELETE_WINDOW", dialog.destroy)  # take over exit
        dialog.transient(self.root)  # set to be dialong rather than main window
        dialog.grab_set()  # prevent input to main window

        # Wait for user to do something
        dialog.wait_window()

        return self.__out

    def doneCB(self, inId):
        # If name is empty, don't try to process anything
        if (self.__name.get() == ""):
            self.__out = None
            return

        # Allow ID to be generated by caller if not selected
        # return 0
        if (self.__id.get() == ""):
            self.__out = [str(self.__name.get()).title(), 0]
            return

        # Check if ID is alreay in use, but only if not editting
        if (inId == ""):
            if (int(str(self.__id.get())) in [s.ID for s in self.students]):
                # If so let the user know and let them restart
                messagebox.showerror("Student ID in use", "The entered student ID is already in use, please try again.")
                self.__out = self.addStudentDialog(inName=self.__name.get())
                return

        self.__out = [str(self.__name.get()).title(), int(str(self.__id.get()))]
        return

    @staticmethod
    def checkID(val: str) -> bool:
        # If ID is empty allow
        if (len(val) == 0):
            return True
        # In anything else make sure is a number
        return val.isnumeric()

    def addGrade(self) -> None:
        pass
